// Makes brain/src/simRoads.ts, the roads the simulated truck (SIM=1) drives:
// each leg of its Phoenix loop routed along real streets by OpenStreetMap
// routing (OSRM on the FOSSGIS servers, the same ones God's Eye View's
// Directions uses), with the road's speed for every stretch.
//   node scripts/bake-sim-roads.mjs
// Run once and commit the result; the brain never calls the router itself
// (DEMO=1 closes the network, and a desk shouldn't need it). FOSSGIS asks for
// one request a second at most, so the legs go one at a time.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'brain/src/simRoads.ts');
const BASE = 'https://routing.openstreetmap.de/routed-car/route/v1/driving';

// Home (Arcadia) -> Tempe -> downtown -> home: the stops of the old hand-drawn loop.
const HOME = [33.4990, -111.9800], TEMPE = [33.4255, -111.9400], DOWNTOWN = [33.4484, -112.0740];
const LEGS = [
  { name: 'Home → Tempe', via: [HOME, TEMPE] },
  { name: 'Tempe → Downtown (freeway)', via: [TEMPE, DOWNTOWN] },
  { name: 'Downtown → Home', via: [DOWNTOWN, HOME] },
];

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const r5 = (n) => Math.round(n * 1e5) / 1e5;

const legs = [];
for (const [i, leg] of LEGS.entries()) {
  if (i) await sleep(1200);
  const coords = leg.via.map(([lat, lon]) => `${lon},${lat}`).join(';');
  const res = await fetch(`${BASE}/${coords}?overview=full&geometries=geojson&annotations=speed`, {
    headers: { 'User-Agent': 'truck-assistant sim-roads bake (github.com/jraben/truck-assistant)' },
  });
  if (!res.ok) throw new Error(`${leg.name}: HTTP ${res.status}`);
  const j = await res.json();
  const route = j.routes?.[0];
  if (j.code !== 'Ok' || !route) throw new Error(`${leg.name}: ${j.code} ${j.message ?? ''}`);
  const speeds = route.legs.flatMap((l) => l.annotation.speed); // m/s, one per segment
  const pts = route.geometry.coordinates.map(([lon, lat], k) => [r5(lat), r5(lon), k < speeds.length ? Math.round(speeds[k] * 2.23694) : 0]);
  legs.push({ name: leg.name, pts });
  console.log(`${leg.name}: ${pts.length} points, ${(route.distance / 1609.344).toFixed(1)} mi, ${Math.round(route.duration / 60)} min`);
}

const body = legs.map((l) => `  { name: ${JSON.stringify(l.name)}, pts: [\n${l.pts.map((p) => `    [${p.join(', ')}],`).join('\n')}\n  ] },`).join('\n');
writeFileSync(out, `// Generated by scripts/bake-sim-roads.mjs: do not edit by hand, run it again.
// Routes from OpenStreetMap data (© OpenStreetMap contributors, ODbL) via OSRM
// on the FOSSGIS servers. Each point is [lat, lon, mph of the road from here to
// the next point]; the last point's mph is 0.

export type SimRoad = { name: string; pts: [number, number, number][] };

export const SIM_ROADS: SimRoad[] = [
${body}
];
`);
console.log(`wrote ${out}`);
