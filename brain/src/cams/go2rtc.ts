// go2rtc on the Pi: the config is generated from remote.json (never hand-edited),
// the binary is pinned by deploy/pi/install.sh, and the brain runs it as a child.
// Browsers never talk to go2rtc's API directly: the brain proxies its WebSocket
// (/api/cams/ws) and its player scripts (/go2rtc/*), so the remote token covers
// them. WebRTC media goes straight to go2rtc's ICE port (LAN / Tailscale).
import { execFile, spawn, type ChildProcess } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import type { CameraConfig } from '../remote/types.ts';

export type Go2rtcPorts = { api: string; rtsp: string; webrtc: string };

const q = (s: string) => JSON.stringify(s); // YAML double-quoted scalars accept JSON strings

/** The ffmpeg test pattern a "test" camera streams (moving, with a frame counter). Hue tells cameras apart. */
export function testPattern(c: CameraConfig, index: number): string {
  const hue = (index * 70) % 360;
  return `testsrc=size=${c.width}x${c.height}:rate=${c.fps},hue=h=${hue}`;
}

/** One go2rtc stream source for a camera. Pure. */
export function streamSource(c: CameraConfig, index: number): string {
  if (c.source === 'rtsp') return c.url!;
  if (c.source === 'test') {
    // exec: go2rtc starts ffmpeg on demand and reads its RTSP output; -re keeps it at real time.
    return `exec:ffmpeg -hide_banner -loglevel error -re -f lavfi -i ${testPattern(c, index)} -c:v libx264 -preset ultrafast -tune zerolatency -pix_fmt yuv420p -g ${c.fps * 2} -f rtsp {output}`;
  }
  // USB webcam or composite/AHD capture stick (both UVC): read it with ffmpeg, encode H.264
  // (#hardware: the Pi 4's v4l2m2m encoder if there is one; the Pi 5 has none and uses x264).
  const params = [`video=${c.device}`];
  if (c.inputFormat !== 'auto') params.push(`input_format=${c.inputFormat}`);
  params.push(`video_size=${c.width}x${c.height}`, `framerate=${c.fps}`);
  return `ffmpeg:device?${params.join('&')}#video=h264#hardware`;
}

/** go2rtc.yaml for the enabled cameras. Pure, so it is unit-tested. */
export function go2rtcConfig(cameras: CameraConfig[], ports: Go2rtcPorts): string {
  const on = cameras.filter((c) => c.enabled);
  const lines = [
    '# Generated by the Slate Cockpit brain from remote.json (/settings > Cameras).',
    '# Edits here are overwritten.',
    'api:',
    `  listen: ${q(ports.api)}`,
    '  origin: "*"',
    'rtsp:',
    `  listen: ${q(ports.rtsp)}`,
    'webrtc:',
    `  listen: ${q(ports.webrtc)}`,
    '  candidates:',
    '    - stun:8555',
    'log:',
    '  level: warn',
    'streams:',
  ];
  if (!on.length) lines.push('  {}');
  on.forEach((c) => {
    lines.push(`  ${c.id}:`);
    lines.push(`    - ${q(streamSource(c, cameras.indexOf(c)))}`);
  });
  return lines.join('\n') + '\n';
}

/** Does `bin -version` run? Resolves to the version line or null. */
export function probeBinary(bin: string, args: string[] = ['-version']): Promise<string | null> {
  return new Promise((resolve) => {
    try {
      execFile(bin, args, { timeout: 5000, windowsHide: true }, (err, stdout, stderr) => {
        if (err && (err as NodeJS.ErrnoException).code === 'ENOENT') return resolve(null);
        const out = `${stdout ?? ''}${stderr ?? ''}`.trim().split(/\r?\n/)[0] ?? '';
        resolve(err && !out ? null : out || 'unknown version');
      });
    } catch { resolve(null); }
  });
}

/** go2rtc as a child process: restarted when it dies (with backoff) and when the config changes. */
export class Go2rtcProcess {
  private child: ChildProcess | null = null;
  private stopped = true;
  private backoff = 1000;
  private timer: NodeJS.Timeout | null = null;
  lastError: string | null = null;
  private bin: string;
  private file: string;
  constructor(bin: string, file: string) { this.bin = bin; this.file = file; }

  get running() { return !!this.child; }

  write(yaml: string) { writeFileSync(this.file, yaml); }

  start() { this.stopped = false; this.spawn(); }

  restart() { if (this.child) this.child.kill(); else if (!this.stopped) this.spawn(); }

  private spawn() {
    if (this.stopped || this.child) return;
    const c = spawn(this.bin, ['-config', this.file], { stdio: ['ignore', 'ignore', 'pipe'], windowsHide: true });
    this.child = c;
    const started = Date.now();
    c.stderr?.on('data', (d: Buffer) => { const l = d.toString().trim(); if (l) { this.lastError = l.split('\n').pop()!.slice(0, 200); console.warn(`[go2rtc] ${this.lastError}`); } });
    c.on('error', (e) => { this.lastError = e.message; });
    c.on('exit', (code) => {
      this.child = null;
      if (this.stopped) return;
      if (Date.now() - started > 30_000) this.backoff = 1000;
      console.warn(`[go2rtc] exited (${code}); restarting in ${this.backoff / 1000} s`);
      this.timer = setTimeout(() => this.spawn(), this.backoff);
      this.backoff = Math.min(this.backoff * 2, 30_000);
    });
  }

  stop() {
    this.stopped = true;
    if (this.timer) clearTimeout(this.timer);
    this.child?.kill();
    this.child = null;
  }
}
